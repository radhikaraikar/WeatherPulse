// Caching structure for compiled dictionaries
const _compiledPhraseCache = {};
const _compiledKeyCache = {};

function getMergedPhrasesForLang(lang) {
  if (_compiledPhraseCache[lang]) {
    return _compiledPhraseCache[lang];
  }

  const result = {};
  const targetDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const enDict = TRANSLATIONS.en;

  // 1. Merge structured key-value pairs where en key has string value
  for (const k in enDict) {
    if (typeof enDict[k] === 'string' && typeof targetDict[k] === 'string') {
      const enStr = enDict[k].trim();
      const targetStr = targetDict[k].trim();
      if (enStr && targetStr) {
        result[enStr] = targetStr;
      }
    }
  }

  // 2. Merge specific phrases
  if (targetDict.phrases) {
    for (const p in targetDict.phrases) {
      const val = targetDict.phrases[p];
      if (typeof val === 'string' && val.trim()) {
        result[p.trim()] = val.trim();
      }
    }
  }

  _compiledPhraseCache[lang] = result;
  return result;
}

function getSortedPhraseKeysForLang(lang) {
  if (_compiledKeyCache[lang]) {
    return _compiledKeyCache[lang];
  }

  const map = getMergedPhrasesForLang(lang);
  const keys = Object.keys(map).sort((a, b) => b.length - a.length);
  _compiledKeyCache[lang] = keys;
  return keys;
}

